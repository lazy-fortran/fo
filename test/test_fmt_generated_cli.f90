program test_fmt_generated_cli
    !! A Fortran source whose first five lines include a comment saying it is
    !! generated and not to be edited is left byte-identical by fo fmt and is
    !! not reported by fo fmt --check. An unmarked source with the same
    !! formatting problem is still reported and rewritten.
    use fo_test_harness, only: string_list_t, process_result_t, list_add
    use fo_test_harness, only: make_scratch, join_path, write_text, read_text, remove_tree
    use fo_test_harness, only: assert_equal_integer, assert_equal_string, assert_true
    use fo_test_harness, only: assert_contains, assert_not_contains, assert_process_ok
    use fo_test_harness, only: finish_assertions
    use fo_test_cli, only: resolve_driver, run_fo
    implicit none

    character(len=*), parameter :: nl = new_line('a')
    character(len=*), parameter :: body = &
        'module probe'//nl//'    implicit none'//nl//'contains'//nl// &
        '    function f(x) &'//nl//'        result(y)'//nl// &
        '        real, intent(in) :: x'//nl//'        real :: y'//nl// &
        '        y = x'//nl//'    end function f'//nl//'end module probe'//nl
    character(:), allocatable :: driver, scratch, project, generated_source, plain_source
    character(:), allocatable :: generated_after, plain_after
    type(process_result_t) :: result
    type(string_list_t) :: command

    call resolve_driver(driver)
    call make_scratch('fo-fmt-generated', scratch)
    project = join_path(scratch, 'project')
    call write_text(join_path(project, 'fpm.toml'), 'name = "generated_probe"'//nl)
    generated_source = '! Generated by gen/probe_gen.f90; do not edit.'//nl//body
    plain_source = '! Hand-written probe.'//nl//body
    call write_text(join_path(project, 'src/generated_probe.f90'), generated_source)
    call write_text(join_path(project, 'src/plain_probe.f90'), plain_source)

    command = words([character(len=32) :: 'fmt', '--check', 'src/generated_probe.f90'])
    call invoke(project, command, result)
    call assert_process_ok(result, 'generated source passes fo fmt --check')

    command = words([character(len=32) :: 'fmt', '--check', 'src/plain_probe.f90'])
    call invoke(project, command, result)
    call assert_equal_integer(result%exit_code, 1, 'unmarked unformatted source fails fo fmt --check')
    call assert_contains(result%stderr, 'needs formatting', 'unmarked source is reported')

    command = words([character(len=32) :: 'fmt', '--check'])
    call invoke(project, command, result)
    call assert_equal_integer(result%exit_code, 1, 'project check still fails on the unmarked source')
    call assert_contains(result%stderr, 'plain_probe.f90:6: needs formatting', &
        'project check names the unmarked source')
    call assert_not_contains(result%stderr, 'generated_probe', &
        'project check does not report the generated source')

    command = words([character(len=32) :: 'fmt'])
    call invoke(project, command, result)
    call assert_process_ok(result, 'fo fmt rewrites the project')
    generated_after = read_text(join_path(project, 'src/generated_probe.f90'))
    plain_after = read_text(join_path(project, 'src/plain_probe.f90'))
    call assert_equal_string(generated_after, generated_source, &
        'fo fmt leaves the generated source byte-identical')
    call assert_true(plain_after /= plain_source, 'fo fmt still rewrites the unmarked source')

    call remove_tree(scratch)
    call finish_assertions()

contains

    function words(items) result(list)
        character(len=*), intent(in) :: items(:)
        type(string_list_t) :: list
        integer :: k

        do k = 1, size(items)
            call list_add(list, trim(items(k)))
        end do
    end function words

    subroutine invoke(directory, arguments, child)
        character(len=*), intent(in) :: directory
        type(string_list_t), intent(in) :: arguments
        type(process_result_t), intent(out) :: child

        call run_fo(driver, arguments, directory, join_path(scratch, '.fo-cache'), child)
    end subroutine invoke

end program test_fmt_generated_cli
